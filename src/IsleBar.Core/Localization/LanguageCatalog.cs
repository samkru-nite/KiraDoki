    /// <summary>Language used when a string cannot be found.</summary>
    public const string Fallback = "en";

    private static readonly ReadOnlyDictionary<string, LanguageStrings> Table = new(BuildTable());

    public static IReadOnlyCollection<string> Codes => Table.Keys;

    public static bool IsKnown(string? code) => code is not null && Table.ContainsKey(code);

    /// <summary>Strings for a language code. Unknown codes get English.</summary>
    public static LanguageStrings For(string? code)
        => code is not null && Table.TryGetValue(code, out var strings) ? strings : Table[Fallback];

